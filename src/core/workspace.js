export function penReachAtHeight(z) {
  if (!Number.isFinite(z) || z < MIN_Z || z > MAX_Z) return null;
  const index = (z - MIN_Z) / 2;
  const lower = Math.floor(index);
  const upper = Math.min(lower + 1, RADII.length / 2 - 1);
  const fraction = index - lower;
  const radius = (offset) => RADII[lower * 2 + offset] * (1 - fraction) + RADII[upper * 2 + offset] * fraction;
  return { innerRadius: radius(1) + PEN_OFFSET + MARGIN, outerRadius: radius(0) + PEN_OFFSET - MARGIN };
}
